"""Collect the engine's own games, so the positions it actually reaches can be labeled.

Human games rarely contain the positions a no-search engine gets into once it is far ahead
(and then shuffles, repeats or stalemates), so the model never learns how to convert them.
Playing the current model against a random mover and against weak Stockfish produces exactly
those positions; `tnsr chess prepare` then labels them with Stockfish like any other PGN
(the same idea as DAgger: train on the states your own policy visits).
"""

from __future__ import annotations

import os
import random
from collections.abc import Callable
from pathlib import Path

import chess
import chess.engine
import chess.pgn

from .data import find_stockfish
from .engine import ChessEngine

COLLECTED_PREFIX = "tnsr-"
COLLECTED_LICENSE = "generated by TNSR (tnsr chess collect); positions labeled by Stockfish"


def _random_opening(rng: random.Random, plies: int) -> chess.Board:
    board = chess.Board()
    for _ in range(plies):
        moves = list(board.legal_moves)
        if not moves:
            break
        board.push(rng.choice(moves))
    return board


def _finish(board: chess.Board, opponent: Callable[[chess.Board], chess.Move], engine: ChessEngine,
            tnsr_white: bool, max_plies: int) -> None:  # fmt: skip
    while not board.is_game_over(claim_draw=True) and board.ply() < max_plies:
        if (board.turn == chess.WHITE) == tnsr_white:
            board.push(engine.best_move(board))
        else:
            board.push(opponent(board))


def _to_pgn(board: chess.Board, site: str, white: str, black: str) -> str:
    game = chess.pgn.Game.from_board(board)
    game.headers["Event"] = "TNSR on-policy collection"
    game.headers["Site"] = site
    game.headers["White"] = white
    game.headers["Black"] = black
    outcome = board.outcome(claim_draw=True)
    game.headers["Result"] = outcome.result() if outcome else "1/2-1/2"
    return str(game) + "\n\n"


def collect_games(
    engine: ChessEngine,
    out: Path,
    *,
    random_games: int = 200,
    stockfish_games: int = 0,
    levels: list[int] | None = None,
    movetime: float = 0.05,
    opening_plies: int = 4,
    max_plies: int = 300,
    seed: int = 0,
    stockfish: str | None = None,
    log: Callable[[str], None] = print,
) -> Path:
    """Write ``random_games`` + ``stockfish_games`` x levels games to ``out`` (a new PGN)."""
    if out.exists():
        raise FileExistsError(f"{out} already exists")
    out.parent.mkdir(parents=True, exist_ok=True)
    rng = random.Random(seed)
    tmp = out.with_suffix(".partial")
    name = f"TNSR {engine.model_id}"
    n = 0
    with tmp.open("w") as fh:
        for g in range(random_games):
            board = _random_opening(rng, opening_plies)
            white = g % 2 == 0
            _finish(board, lambda b: rng.choice(list(b.legal_moves)), engine, white, max_plies)
            site = f"tnsr:{seed}:random:{g}"
            fh.write(_to_pgn(board, site, *((name, "random") if white else ("random", name))))
            n += 1
            if (g + 1) % 50 == 0:
                log(f"{g + 1}/{random_games} games vs random mover")
        if stockfish_games and levels:
            limit = chess.engine.Limit(time=movetime)
            with chess.engine.SimpleEngine.popen_uci(find_stockfish(stockfish)) as sf:

                def reply(b: chess.Board) -> chess.Move:
                    move = sf.play(b, limit).move
                    assert move is not None
                    return move

                for level in levels:
                    sf.configure({"UCI_LimitStrength": True, "UCI_Elo": level})
                    for g in range(stockfish_games):
                        board = _random_opening(rng, opening_plies)
                        white = g % 2 == 0
                        _finish(board, reply, engine, white, max_plies)
                        site = f"tnsr:{seed}:sf{level}:{g}"
                        opp = f"Stockfish {level}"
                        fh.write(_to_pgn(board, site, *((name, opp) if white else (opp, name))))
                        n += 1
                    log(f"{stockfish_games} games vs Stockfish {level}")
    if out.exists():  # appeared while we were playing: never replace it
        raise FileExistsError(f"{out} already exists; collected games left in {tmp}")
    os.replace(tmp, out)
    log(f"wrote {n} games to {out}")
    return out
